import nodemailer from 'nodemailer';

const host = process.env.SMTP_HOST || 'smtp.gmail.com';
const port = Number(process.env.SMTP_PORT) || 465;
const secure = process.env.SMTP_SECURE === 'true' || port === 465;
const user = process.env.SMTP_USER;
const pass = (process.env.SMTP_PASS || '').replace(/\s+/g, '');
const from = process.env.SMTP_FROM || user;

// Allow destination address from CLI argument, otherwise send to own account
const recipient = process.argv[2] || user;

console.log('--- Checkpoint SMTP Verification Script ---');
console.log(`Driver:   ${process.env.MAIL_DRIVER || 'smtp'}`);
console.log(`Host:     ${host}:${port} (secure: ${secure})`);
console.log(`User:     ${user || '(not set)'}`);
console.log(`From:     ${from}`);
console.log(`To:       ${recipient}`);
console.log('--------------------------------------------\n');

if (!user || !pass) {
  console.error('Error: SMTP_USER and SMTP_PASS must be defined in your .env file.');
  process.exit(1);
}

const transporter = nodemailer.createTransport({
  host,
  port,
  secure,
  auth: { user, pass },
});

async function main() {
  try {
    console.log('[1/2] Testing SMTP connection & credentials...');
    await transporter.verify();
    console.log('      Handshake successful! Credentials accepted by Gmail.\n');

    console.log(`[2/2] Transmitting test email to "${recipient}"...`);
    const info = await transporter.sendMail({
      from,
      to: recipient,
      subject: 'Checkpoint SMTP Test - ' + new Date().toLocaleTimeString(),
      text: `Hello!\n\nThis is a verification email from your Checkpoint backend SMTP setup.\nTimestamp: ${new Date().toISOString()}\n\nIf you see this, your Gmail SMTP integration is working flawlessly!`,
      html: `
        <div style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; max-width: 540px; padding: 24px; border: 1px solid #e2e8f0; border-radius: 8px;">
          <h2 style="color: #0f172a; margin-top: 0;">SMTP Test Successful</h2>
          <p style="color: #334155; line-height: 1.5;">Your Checkpoint backend is properly connected to Gmail SMTP.</p>
          <div style="background-color: #f8fafc; border: 1px solid #e2e8f0; border-radius: 6px; padding: 12px 16px; margin: 16px 0; font-size: 13px;">
            <div><strong>Sender:</strong> ${from}</div>
            <div><strong>Recipient:</strong> ${recipient}</div>
            <div><strong>Timestamp:</strong> ${new Date().toISOString()}</div>
            <div><strong>Status:</strong> <span style="color: #16a34a; font-weight: 600;">Delivered</span></div>
          </div>
          <p style="color: #64748b; font-size: 12px; margin-bottom: 0;">Automated test message generated by Checkpoint scripts/test-mail.js</p>
        </div>
      `,
    });

    console.log('      Email successfully dispatched!');
    console.log(`      Message ID: ${info.messageId}`);
    if (info.response) {
      console.log(`      Server response: ${info.response}`);
    }
    console.log('\nAll checks passed! Your email service is ready.');
  } catch (err) {
    console.error('\nTransmission failed:');
    console.error(err.message || err);

    if (err.code === 'EAUTH' || (err.message && err.message.includes('535'))) {
      console.error('\nTroubleshooting Tip:');
      console.error('Gmail rejected the credentials. Verify that:');
      console.error('1. You are using a 16-character Google App Password (not your normal Google account password).');
      console.error('2. 2-Step Verification remains enabled on the Gmail account.');
    } else if (err.code === 'ESOCKET' || err.code === 'ETIMEDOUT') {
      console.error('\nTroubleshooting Tip:');
      console.error('Network timeout. Check that port 465 (SSL) or 587 (TLS) is not blocked by a local firewall or proxy.');
    }
    process.exit(1);
  }
}

main();

